async def _make_context(browser, auth_session_path: Optional[str]) -> BrowserContext:
    """Create a browser context, optionally loading a stored session."""
    if auth_session_path and os.path.exists(auth_session_path):
        try:
            ctx = await browser.new_context(storage_state=auth_session_path)
            logger.info(f"[CRAWLER] Loaded auth session from {auth_session_path}")
            return ctx
        except Exception as e:
            logger.warning(f"[CRAWLER] Failed to load session: {e}")
    return await browser.new_context()


def _normalize_url(url: str, base_url: str) -> Optional[str]:
    """
    Normalise a URL:
      - Must be within the same origin as base_url
      - Strip query params and fragments (crawl each path once)
      - Return None if external or non-HTTP
    """
    try:
        base_parsed = urlparse(base_url)
        parsed = urlparse(url)

        # Must be same origin
        if parsed.scheme not in ("http", "https"):
            return None
        if parsed.netloc and parsed.netloc != base_parsed.netloc:
            return None

        # Reconstruct clean URL (no query/fragment)
        clean = f"{base_parsed.scheme}://{base_parsed.netloc}{parsed.path}"
        # Drop trailing slash duplicates
        if clean.endswith("/") and clean != base_url.rstrip("/") + "/":
            clean = clean.rstrip("/")
        return clean
    except Exception:
        return None
